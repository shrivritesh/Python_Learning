""" 
**Assignment operators**

Assignment operators are used to assign values to the variables.
This operator is used to assign the value of the right side of the expression to the left side operand.

"""
#eg: 

a = 10
b = a
print(b) # 10
b += a #20
print(b) # 20
b -= a #10
print(b) #10
b *= a #100
print(b) #100
